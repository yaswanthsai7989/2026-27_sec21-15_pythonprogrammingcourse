#Write a python program to demonstrate string creation and basic operations (concatenation, repetition, slicing)
str1 = "Hello"
str2 = "World"
# Concatenation
result = str1 + " " + str2
print("Concatenated string:", result)
# Repetition
repeated = str1 * 3
print("Repeated string:", repeated)
# Slicing
sliced = str1[1:4]
print("Sliced string:", sliced)