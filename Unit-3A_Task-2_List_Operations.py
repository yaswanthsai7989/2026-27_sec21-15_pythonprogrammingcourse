#Write a python program to perform list operations (insert, append, remove, sort, reverse)
my_list = [5, 2, 8, 1, 9]
print("Original list:", my_list)

# Append operation
my_list.append(10)
print("After append:", my_list)

# Insert operation
my_list.insert(2, 3)
print("After insert:", my_list)

# Remove operation
my_list.remove(8)
print("After remove:", my_list)

# Sort operation
my_list.sort()
print("After sort:", my_list)

# Reverse operation
my_list.reverse()
print("After reverse:", my_list)